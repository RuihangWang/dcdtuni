#!/usr/bin/env python3
"""Gate the adjoint-exactness and single-seed closure numbers against E10's own record.

Why this gate exists.  A round-6 review found that the paper's central exactness claim -- the
adjoint matching central differences to a worst per-block median of 1.45e-7 -- and the
single-seed closure figure of 1.19e-4 that the closure floor is contrasted against, existed
NOWHERE in a shipped artifact.  They were prose, traceable only to a Markdown table in
`ddl/docs/AI_DESIGN_PLAN.md` citing a gitignored loggers directory.  Contribution (v) claims
every number in the results appendix is generated by committed scripts reading record JSONs;
these two were the exception, and they were the two the abstract leads with.

`records/e10_adjoint.json` is now the shipped copy of
`ddl/case/benchB/E10_geom_relax/loggers/e10_first/results_e10_geom_relax.json`, and every claim
below is anchored to the sentence that makes it.  Zero matches is a failure: an anchor that stops
matching is a gate that has gone dead, and the prose moving is the usual reason.

Note on scoping: `$1.19\\times10^{-4}$` (E10's single-seed closure gap) and `$1.19\\times10^{-7}$`
(E11e's replication p-value) are different quantities sharing three significant digits.  A
document-wide substring check cannot tell them apart, which is why every pattern here carries the
sentence around it.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent


def claim_scoped(src, specs, problems, where):
    for pattern, expected, label in specs:
        hits = re.findall(pattern, src, re.S)
        if not hits:
            problems.append(f"{where}: nothing in main.tex matches the claim pattern for {label}, "
                            "so that number is unchecked -- the prose moved or the anchor is "
                            "wrong, and a check with nothing to check is not a pass")
            continue
        if isinstance(expected, tuple):
            want = tuple(str(e) for e in expected)
            bad = [h for h in hits if tuple(h) != want]
            shown = " / ".join(want)
        else:
            ok = {str(expected)} if isinstance(expected, (str, int, float)) else {str(e) for e in expected}
            flat = [h if isinstance(h, str) else " / ".join(h) for h in hits]
            bad = [h for h in flat if h not in ok]
            shown = ", ".join(sorted(ok)[:4])
        if bad:
            problems.append(f"{where}: {len(bad)} of {len(hits)} statements of {label} disagree "
                            f"with the record: {sorted(set(map(str, bad)))[:4]} against {shown}")
        else:
            print(f"  {where}: {label} -- all {len(hits)} statement(s) agree with the record")


def sci(v, sig=3):
    """1.4515840814092048e-07 -> ('1.45', '-7'), i.e. mantissa and exponent as the paper prints them."""
    m, e = f"{v:.{sig - 1}e}".split("e")
    return m, str(int(e))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--record", default=str(HERE / "records" / "e10_adjoint.json"))
    ap.add_argument("--tex", default=str(HERE / "main.tex"))
    args = ap.parse_args()

    rp = Path(args.record)
    if not rp.exists():
        print(f"FAIL: no E10 record at {rp}. The adjoint-exactness number in the abstract would "
              "be prose with no artifact behind it, which is the defect this gate closes.",
              file=sys.stderr)
        return 2
    rec = json.loads(rp.read_text())
    src = Path(args.tex).read_text()
    problems = []

    g1 = rec.get("gate1_identity") or {}
    g2 = rec.get("gate2_adjoint_fd") or {}
    g3 = rec.get("gate3_closure") or {}
    g4 = rec.get("gate4_informative") or {}
    rows = {r["block"]: r for r in g2.get("rows", [])}

    # ---- structural: the record must actually say what the paper says it says ----
    if not rec.get("all_gates_pass"):
        problems.append("e10: the record's own all_gates_pass is false, so the paper may not "
                        "present E10 as a passed verification")
    if g1.get("worst_rel_diff") != 0.0:
        problems.append(f"e10: gate-1 straight-through identity worst_rel_diff is "
                        f"{g1.get('worst_rel_diff')}, not exactly 0.0")
    if g2.get("n_unexplained") != 0:
        problems.append(f"e10: {g2.get('n_unexplained')} finite-difference outlier(s) are "
                        "unexplained; the paper's kink-classification protocol claims none are")
    outs = g2.get("outliers") or []
    if outs and any(o.get("verdict") != "kink_of_newton_trip_count" for o in outs):
        problems.append(f"e10: an outlier carries verdict "
                        f"{[o.get('verdict') for o in outs]}, which is not the kink classification "
                        "the paper names")
    if outs and any(o.get("shrinks_with_h") for o in outs):
        problems.append("e10: an outlier's error shrinks with h, so it is a step-size artefact and "
                        "not a kink; calling it a kink would be wrong")
    if not g2.get("pass"):
        problems.append("e10: gate-2 (adjoint vs central differences) did not pass")

    worst_block = max(rows.values(), key=lambda r: r["median_rel_err"]) if rows else None
    if worst_block and f"{g2.get('median_worst')!r}" != f"{worst_block['median_rel_err']!r}":
        problems.append("e10: median_worst is not the maximum of the four per-block medians, so "
                        "'worst per-block median' does not mean what the paper says it means")

    m_w, e_w = sci(g2["median_worst"]) if g2.get("median_worst") is not None else (None, None)
    m_c, e_c = sci(g3["gap_at_shipped_floor"]) if g3.get("gap_at_shipped_floor") is not None else (None, None)
    pl = rows.get("q_placement", {})
    m_p, e_p = sci(pl["median_rel_err"]) if pl.get("median_rel_err") is not None else (None, None)

    specs = [
        (r"worst per-block median of\s*\$([\d.]+)\\times10\^\{" + e_w + r"\}\$", m_w,
         "the worst per-block median adjoint-vs-central-difference error"),
        (r"per-block median \$([\d.]+)\\times10\^\{" + e_w + r"\}\$, whose first-order prediction "
         r"matches\s*the re-solve in sign on all (\d+) decisions tested \(\$\\rho = ([\d.]+)\$\)",
         (m_w, g4.get("n_moves"), f"{g4.get('spearman_rho'):.3f}"),
         "the adjoint median quoted with the sign-agreement count and rank correlation beside it"),
        (r"\$([\d.]+)\\times10\^\{" + e_p + r"\}\$ \(placement, \$n=(\d+)\$\)",
         (m_p, pl.get("n")), "the placement block's median and its coordinate count"),
        (r"against the \$([\d.]+)\\times10\^\{" + e_c + r"\}\$ a single seed gives", m_c,
         "the single-seed closure gap the 311-design floor is contrasted against"),
        (r"of \$([\d.]+)\\times10\^\{" + e_c + r"\}\$ on\s*the one seed E10 measured", m_c,
         "the single-seed closure gap in the contributions list"),
        (r"\$([\d.]+)\\times10\^\{" + e_c + r"\}\$ relative over three designs of one seed", m_c,
         "the single-seed closure gap in section 3"),
    ]
    specs = [s for s in specs if s[1] is not None and
             (not isinstance(s[1], tuple) or all(x is not None for x in s[1]))]
    claim_scoped(src, specs, problems, "e10")

    # The sign agreement must be perfect for the paper to say "all 35".
    if g4.get("sign_agreement") != 1.0:
        problems.append(f"e10: sign agreement is {g4.get('sign_agreement')}, not 1.0, so 'matches "
                        "the re-solve in sign on all 35 decisions' is false")

    if problems:
        print("E10 GATE FAILED:", file=sys.stderr)
        for pr in problems:
            print("  -", pr, file=sys.stderr)
        return 1
    print(f"e10 numbers agree with {rp.name}: worst per-block median {m_w}e{e_w} over "
          f"{sum(r['n'] for r in rows.values())} coordinates in {len(rows)} blocks, "
          f"{g4.get('n_moves')} decisions at sign agreement {g4.get('sign_agreement')}, "
          f"{len(outs)} classified kink outlier(s), single-seed closure {m_c}e{e_c}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
