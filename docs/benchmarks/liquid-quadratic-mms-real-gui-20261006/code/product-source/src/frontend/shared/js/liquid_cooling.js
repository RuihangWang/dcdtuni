/**
 * Liquid cooling system helpers.
 * State lives in V4-native storage: runDefaults.liquid (enabled/inheritResults/solver),
 * models.materialModels.fluids (coolant), constructions.liquidFlowNetworks.net_main (piping),
 * and the transient state.liquidResults (solver output, never serialized). Reached via the
 * window._liqCfg / window._liqFluid / window._liqSetFluid / window._liqNetMain helpers
 * defined in STL_generate.html. This keeps undo/redo and project save/load working.
 */

var _lcAbortController = null;

// Fluid property presets
const _LC_FLUIDS = {
  'water':     { type: 'water',     rho: 992.2, mu: 0.000653, cp: 4180, k: 0.632 },
  'water20C':  { type: 'water20C',  rho: 998.2, mu: 0.001002, cp: 4182, k: 0.600 },
  'glycol_25': { type: 'glycol_25', rho: 1032,  mu: 0.0018,   cp: 3850, k: 0.48  },
  'glycol_50': { type: 'glycol_50', rho: 1065,  mu: 0.004,    cp: 3350, k: 0.37  }
};

/**
 * Enable/disable liquid cooling system globally.
 */
window.setLiquidCoolingEnabled = function(enabled) {
  pushUndoCheckpoint('setLiquidCoolingEnabled');
  window._liqCfg().enabled = !!enabled;
  updateUI();
  logOperation('setLiquidCoolingEnabled', `Liquid cooling ${enabled ? 'enabled' : 'disabled'}`, {enabled}, 'modify');
};

/**
 * Set coolant fluid type and auto-fill properties.
 */
window.setLiquidCoolingFluid = function(fluidType) {
  pushUndoCheckpoint('setLiquidCoolingFluid');
  if (fluidType !== 'custom') {
    window._liqSetFluid(_LC_FLUIDS[fluidType] || _LC_FLUIDS['water']);
  }
  _syncFluidInputs();
  updateUI();
  logOperation('setLiquidCoolingFluid', `Set coolant to ${fluidType}`, {fluidType}, 'modify');
};

window.updateFluidProp = function(key, value) {
  if (!state) return;
  pushUndoCheckpoint('updateFluidProp');
  // Read the current fluid (or seed from water), mutate, mark custom, then write it back
  // re-keyed in the fluids dict (the dict key tracks fluid.type, so it must be rewritten).
  var fluid = Object.assign({}, window._liqFluid() || _LC_FLUIDS['water']);
  fluid[key] = value;
  fluid.type = 'custom';
  window._liqSetFluid(fluid);
  var sel = document.getElementById('lc-fluid-select');
  if (sel) sel.value = 'custom';
  logOperation('updateFluidProp', `Fluid ${key} = ${value}`, {key, value}, 'modify');
};

window._syncFluidInputs = function _syncFluidInputs() {
  if (!state) return;
  var f = window._liqFluid() || {};
  var el;
  el = document.getElementById('lsm-fluid-rho'); if (el) el.value = f.rho || 992.2;
  el = document.getElementById('lsm-fluid-cp');  if (el) el.value = f.cp  || 4180;
  el = document.getElementById('lsm-fluid-mu');  if (el) el.value = f.mu  || 0.000653;
  el = document.getElementById('lsm-fluid-k');   if (el) el.value = f.k   || 0.632;
}

/**
 * Build the liquidCooling section of the .cfdrun manifest JSON.
 * Called from buildCfdrunJson().
 */
window.buildLiquidCoolingExport = function(models) {
  // V4-native reconstruction of the legacy liquidCooling export shape. The fields this
  // consumer reads are rebuilt from their V4 homes: enabled+fluid from runDefaults.liquid /
  // materialModels.fluids, piping from net_main. `specifications` has no V4 home (the old
  // alias never defined it either, so it read undefined) — preserve that exactly.
  if (!window._liqCfg().enabled) return null;
  const _fluid = window._liqFluid();
  const _nm = window._liqNetMain(false);
  const _piping = {
    autoGenerated: _nm ? _nm.autoGenerated : undefined,
    mainPipeSpec:  _nm ? _nm.mainPipeSpec  : null,
    branchPipeSpec: _nm ? _nm.branchPipeSpec : null,
    chains: (_nm && Array.isArray(_nm.chains)) ? _nm.chains : []
  };
  const _specifications = undefined;

  const cdus = {};
  models.forEach(m => {
    if (m.kind !== 'cdu' || !m.meta.enabled) return;
    const name = window.sanitizeName ? window.sanitizeName(m.meta.name) : m.meta.name.replace(/[^A-Za-z0-9_]/g, '_');
    const mGeom = m.geometry || {};
    const mLoc  = mGeom.location || {};
    const mSize = mGeom.size || {};
    const cool  = m.cooling || {};
    const cons  = m.constructions || {};
    const advancedMode = cool.advancedMode;
    const advanced = { heatExchanger: cons.heatExchanger, pump: cons.pump, valve: cons.valve };
    cdus[name] = {
      geometry: {
        anchor: { ...mLoc },
        size: { W: mSize.x, D: mSize.z, H: mSize.y }
      },
      supplyTemperature: cool.supplyTemperatureC || 35,
      totalFlowRate:     cool.totalFlowRate      || 60,
      servedRacks:       (m.meta && m.meta.racks) || [],
      advanced: advancedMode ? advanced : undefined
    };
  });

  return {
    enabled: true,
    fluid: { ..._fluid },
    cdus: cdus,
    // _specifications has no V4 home and is always undefined (see above); the old
    // alias likewise produced `undefined` here. Deep-cloning undefined via
    // JSON.parse(JSON.stringify(...)) throws ("undefined" is not valid JSON), so
    // preserve the undefined value directly and only clone a real object.
    specifications: (typeof _specifications === 'undefined')
      ? undefined
      : JSON.parse(JSON.stringify(_specifications)),
    piping: { ..._piping }
  };
};

/**
 * Export .liquidrun graph JSON and save to server.
 * Called before runLiquidSolve().
 */
window.exportLiquidrun = async function() {
  if (!window.buildLiquidrunJson) {
    alert('liquid_graphgen.js not loaded');
    return null;
  }
  // buildLiquidrunJson reads only liquidState.fluid and liquidState.solver — supply a
  // minimal V4-native view instead of the legacy whole liquidCooling object.
  var liqCfg = window._liqCfg();
  var liquidState = { fluid: window._liqFluid(), solver: liqCfg.solver, enabled: liqCfg.enabled };
  var graph = window.buildLiquidrunJson(window.allModels(), liquidState);
  if (!graph) return null;

  try {
    var resp = await fetch('/api/liquid/export-liquidrun', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(graph)
    });
    var data = await resp.json();
    if (resp.ok) {
      if (window.logOperation) logOperation('exportLiquidrun', 'Exported .liquidrun: ' + (data.projectName || ''), {nodes: graph.nodes.length, edges: graph.edges.length}, 'file');
      return graph;
    } else {
      alert(t('liquid.export_failed') + ': ' + (data.error || 'Unknown'));
      return null;
    }
  } catch (e) {
    alert('导出错误: ' + e.message);
    return null;
  }
};

/**
 * Run ODIL liquid cooling solver via server API with SSE streaming.
 * Exports .liquidrun first, then streams per-epoch progress.
 */
window._lcSetSolveButtons = function(running) {
  var runBtn = document.getElementById('lc-run-btn');
  var stopBtn = document.getElementById('lc-stop-btn');
  if (runBtn) runBtn.style.display = running ? 'none' : '';
  if (stopBtn) stopBtn.style.display = running ? '' : 'none';
};

window.runLiquidSolve = async function() {
  var exported = await window.exportLiquidrun();
  if (!exported) return null;

  if (window.lsmLoadCPList) window.lsmLoadCPList(exported);

  var lsmRight = document.getElementById('liquid-solver-monitoring-right');
  if (lsmRight) lsmRight.style.display = 'flex';

  var monCfg = window.lsmGetMonitoringConfig ? window.lsmGetMonitoringConfig() : { loss: true, cpList: [] };
  if (window._lsmStartMonitoring) window._lsmStartMonitoring(monCfg);

  var solverCfg = window._liqCfg().solver || {};

  _lcAbortController = new AbortController();
  window._lcSetSolveButtons(true);
  if (typeof window._setGlobalUIFrozen === 'function') window._setGlobalUIFrozen(true);

  try {
    var resp = await fetch('/api/liquid/solve', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        device: solverCfg.device || 'cpu',
        monitor_cps: monCfg.cpList.map(function(cp) { return cp.id; })
      }),
      signal: _lcAbortController.signal
    });

    if (!resp.ok) {
      var errText = await resp.text();
      alert(t('liquid.solve_failed') + ': ' + errText);
      window._lcSetSolveButtons(false);
      if (typeof window._setGlobalUIFrozen === 'function') window._setGlobalUIFrozen(false);
      return null;
    }

    var reader = resp.body.getReader();
    var decoder = new TextDecoder();
    var buffer = '';
    var lastData = null;

    while (true) {
      var chunk = await reader.read();
      if (chunk.done) break;
      buffer += decoder.decode(chunk.value, { stream: true });

      var lines = buffer.split('\n');
      buffer = lines.pop();
      for (var i = 0; i < lines.length; i++) {
        var line = lines[i].trim();
        if (line.startsWith('data: ')) {
          try {
            var payload = JSON.parse(line.substring(6));
            lastData = payload;
            if (window._lsmOnSSE) window._lsmOnSSE(payload);
          } catch (parseErr) {
            console.warn('[liquid_cooling] SSE parse error:', parseErr);
          }
        }
      }
    }

    window._lcSetSolveButtons(false);
    if (typeof window._setGlobalUIFrozen === 'function') window._setGlobalUIFrozen(false);
    _lcAbortController = null;

    if (lastData && lastData.stage === 'done') {
      if (window.logOperation) logOperation('runLiquidSolve', 'ODIL solved', {converged: lastData.converged, epochs: lastData.epochs}, 'file');
      try {
        var resResp = await fetch('/api/liquid/results');
        if (resResp.ok) {
          var fullResults = await resResp.json();
          state.liquidResults = fullResults;
        } else {
          state.liquidResults = lastData;
        }
      } catch (_e) {
        state.liquidResults = lastData;
      }
      if (window._refreshLiquidResultsPanel) window._refreshLiquidResultsPanel();
      if (window._lsmShowPostProcessHint) window._lsmShowPostProcessHint();
      if (window.scanCaseStatus) window.scanCaseStatus();
      return state.liquidResults;
    } else if (lastData && lastData.stage === 'error') {
      alert(t('liquid.solve_error') + ': ' + (lastData.message || 'Unknown'));
      return null;
    }

    return lastData;
  } catch (e) {
    window._lcSetSolveButtons(false);
    if (typeof window._setGlobalUIFrozen === 'function') window._setGlobalUIFrozen(false);
    _lcAbortController = null;
    if (e.name === 'AbortError') {
      if (window.logOperation) logOperation('stopLiquidSolve', 'Liquid solve aborted by user', {}, 'modify');
      return null;
    }
    alert(t('liquid.solve_error') + ': ' + e.message);
    return null;
  }
};

window.stopLiquidSolve = function() {
  if (_lcAbortController) {
    _lcAbortController.abort();
    _lcAbortController = null;
  }
  window._lcSetSolveButtons(false);
  if (typeof window._setGlobalUIFrozen === 'function') window._setGlobalUIFrozen(false);
  if (window.logOperation) logOperation('stopLiquidSolve', 'User requested liquid solve stop', {}, 'modify');
};

/**
 * Fetch cached liquid results from server.
 */
window.fetchLiquidResults = async function() {
  try {
    const resp = await fetch('/api/liquid/results');
    if (resp.ok) {
      const data = await resp.json();
      state.liquidResults = data;
      return data;
    }
    return null;
  } catch (e) {
    return null;
  }
};

/**
 * Toggle a rack in/out of a CDU's servedRacks list.
 */
window.toggleCduServedRack = function(modelId, rackName, checked) {
  const model = _modelMap.get(modelId);
  if (!model || model.kind !== 'cdu' || !model.meta) return;
  pushUndoCheckpoint('toggleCduServedRack');
  if (!model.meta.racks) model.meta.racks = [];
  const arr = model.meta.racks;
  const idx = arr.indexOf(rackName);
  if (checked && idx === -1) arr.push(rackName);
  if (!checked && idx !== -1) arr.splice(idx, 1);
  updateUI();
  logOperation('toggleCduServedRack', `CDU ${model.meta.name}: ${checked ? 'added' : 'removed'} ${rackName}`, {rackName, checked}, 'modify');
};

