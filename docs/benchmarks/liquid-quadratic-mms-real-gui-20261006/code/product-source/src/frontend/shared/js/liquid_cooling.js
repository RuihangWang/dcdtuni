/**
 * Query the server for available liquid results and update the inheritance status panel.
 */
window.refreshLiquidInheritanceStatus = async function() {
  try {
    const resp = await fetch('/api/liquid/results');
    if (!resp.ok) {
      const statusEl = document.getElementById('lc-inherit-status');
      if (statusEl) statusEl.textContent = t('liquid.inherit_no_results');
      const detailsEl = document.getElementById('lc-inherit-details');
      if (detailsEl) detailsEl.style.display = 'none';
      return;
    }
    const data = await resp.json();
    const servers = data.servers || {};
    const count = Object.keys(servers).length;
    let maxT = 0;
    Object.values(servers).forEach(s => {
      if (s && s.chip_max_temp_C > maxT) maxT = s.chip_max_temp_C;
    });
    const summary = document.getElementById('lc-inherit-summary');
    if (summary) {
      // Was a hard-coded bilingual string, so this line ignored the language
      // setting while every label around it followed it.
      summary.innerHTML = t('liquid.inherit_servers') + ': ' + count +
        '<br>' + t('liquid.inherit_max_chip') + ': ' + maxT.toFixed(1) + '°C';
    }
    const statusEl = document.getElementById('lc-inherit-status');
    if (statusEl) statusEl.textContent = t('liquid.inherit_loaded');
    const detailsEl = document.getElementById('lc-inherit-details');
    if (detailsEl) detailsEl.style.display = '';
  } catch(e) {
    const statusEl = document.getElementById('lc-inherit-status');
    if (statusEl) statusEl.textContent = 'Error: ' + e.message;
  }
};

