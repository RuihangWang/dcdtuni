#!/usr/bin/env python3
"""Generate web/src/aiRanges.ts from the model bundle's own data.

Two things the UI needs and must not hard-code:

* the slider BOUNDS the C1 checkpoint was trained on (from dataset/meta.json's ui_ranges,
  which compute_ui_ranges.py measured over 677 training cases / 214,366 server slots), and
* the per-rack SERVER SLOT map plus each slot's baseline operating point, read from the
  demo case's own boundary_conditions.json — that file is authoritative (model.json
  disagrees with it and is wrong).

Regenerate after changing the bundle:  python scripts/gen_ai_ranges.py
"""
import collections
import json
import os

DEMO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_DS = os.environ.get("DC_CFD_GTC_DATASET",
                     "/mnt/lv/home/Public/GTC/processed_dataset_unconverged")
BC = os.path.join(_DS, "case0", "boundary_conditions.json")
META = os.path.join(DEMO, "data", "GTC_TransFVGN_FronzenText", "dataset", "meta.json")
OUT = os.path.join(DEMO, "web", "src", "aiRanges.ts")

HEADER = '''// GENERATED by scripts/gen_ai_ranges.py — do not edit by hand.
//
// Slider bounds measured over the C1 training split (677 cases / 214,366 server slots),
// and the per-rack server-slot map + baseline operating point read from the demo case's
// own boundary_conditions.json. The UI can therefore only ask the model for operating
// points it was actually trained on.
//
// IMPORTANT: the model never sees watts. Power reaches it only as
//     temperatureDelta_K = P / (RHO_CP * Q)
// so a (P, Q) pair whose marginals are both in range can still be an out-of-distribution
// delta-T. Always surface the derived delta-T and bound on that too.
'''


def r6(x):
    return round(float(x), 6)


def band(d, keys=("min", "p1", "p5", "median", "p95", "p99", "max")):
    return "{ " + ", ".join(f"{k}: {r6(d[k])}" for k in keys
                            if k in d and d[k] is not None) + " }"


def main():
    with open(BC) as f:
        bc = json.load(f)
    with open(META) as f:
        ui = json.load(f)["ui_ranges"]

    slots = collections.defaultdict(list)
    for key in bc["server_powers"]:
        rack, _, n = key.rpartition("_server_slot_")
        slots[rack].append(int(n))
    for r in slots:
        slots[r].sort()
    acus = sorted(bc["supply_air_temperatures"])

    L = [HEADER]
    L.append(f"export const RHO_CP = {ui['rho_cp']};")
    L.append(f"export const RHO_AIR = {ui['rho_air']};\n")
    L.append("/** Server temperature rise — the ONLY channel power reaches the model by. */")
    L.append("export const deltaT = (powerW: number, flowM3s: number) =>")
    L.append("  powerW / (RHO_CP * Math.max(flowM3s, 1e-9));\n")
    for name, key in (("POWER_W", "power_W"), ("FLOW_M3S", "flow_m3s"),
                      ("DELTA_T_K", "delta_T_K"), ("ACU_T_C", "acu_supply_T_C"),
                      ("ACU_FLOW_M3S", "acu_supply_flow_m3s")):
        L.append(f"export const {name} = {band(ui[key])};")
    L.append("")
    L.append("/** rack prim name -> its server slot numbers (5-7 per rack, 317 total). */")
    L.append("export const RACK_SLOTS: Record<string, number[]> = {")
    for r in sorted(slots):
        L.append(f'  "{r}": {json.dumps(slots[r])},')
    L.append("};\n")
    L.append("export const ACU_NAMES: string[] = [")
    for a in acus:
        L.append(f'  "{a}",')
    L.append("];\n")
    L.append("export const slotKey = (rack: string, n: number) =>")
    L.append("  `${rack}_server_slot_${n}`;\n")
    L.append("/** The demo case's own operating point — sliders start here. */")
    for name, src in (("BASE_SERVER_POWER", bc["server_powers"]),
                      ("BASE_SERVER_FLOW", bc["server_volume_flow_rates"]),
                      ("BASE_ACU_T", bc["supply_air_temperatures"]),
                      ("BASE_ACU_FLOW", bc["supply_air_volume_flow_rates"])):
        L.append(f"export const {name}: Record<string, number> = {{")
        for k, v in sorted(src.items()):
            L.append(f'  "{k}": {r6(v)},')
        L.append("};")

    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {OUT}")
    print(f"  racks={len(slots)} slots={sum(len(v) for v in slots.values())} acus={len(acus)}")


if __name__ == "__main__":
    main()
