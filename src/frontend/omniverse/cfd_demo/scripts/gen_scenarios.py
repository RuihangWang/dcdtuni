#!/usr/bin/env python3
"""Pick demo scenarios from the dataset and emit web/src/scenarios.ts.

Why dataset cases rather than synthesised operating points: the numerical (A3) arm reads
its boundary condition from the per-face t=1 field, which every dataset case already
carries. Serving one needs no OpenFOAM run, and its response is verified — three cases
predict visibly different, physically sane fields (293-322 K).

A synthesised operating point would force a fresh 1-step solve, and a control run showed
that path is not yet faithful: a 0.1% power change moved the field as much as a 50% one,
i.e. the difference came from our solver step rather than from the boundary condition,
and the prediction left the physical range. So the demo uses cases we can stand behind.

Scenarios are chosen to SPREAD on total IT load, so consecutive picks look different in
the viewport rather than being three samples of the same operating point.
"""
import json
import os
import statistics

DEMO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The dataset lives outside the repo and is machine-specific. Without this override a
# clone elsewhere silently produced an EMPTY scenario list: os.path.exists returns
# False for every case, summarise() returns None throughout, and nothing warns.
SRC = os.environ.get("DC_CFD_GTC_DATASET",
                     "/mnt/lv/home/Public/GTC/processed_dataset_unconverged")
OUT = os.path.join(DEMO, "web", "src", "scenarios.ts")
RHO_CP = 1197.14
N_PICK = int(os.environ.get("N_SCENARIOS", "6"))


def summarise(case):
    p = os.path.join(SRC, case, "boundary_conditions.json")
    if not os.path.exists(p):
        return None
    with open(p) as f:
        bc = json.load(f)
    pw = list(bc.get("server_powers", {}).values())
    q = list(bc.get("server_volume_flow_rates", {}).values())
    t = list(bc.get("supply_air_temperatures", {}).values())
    if not pw or not q:
        return None
    dt = [a / (RHO_CP * b) for a, b in zip(pw, q) if b]
    return {
        "case": case,
        # Full per-slot maps, not just the summary. The UI ALWAYS posts a populated bc,
        # so the worker's `case` field never wins — a scenario is only meaningful if
        # picking it LOADS that operating point into the sliders. Without these the
        # dropdown was dead UI: it changed the label and nothing else.
        "bc": {
            "server_powers": bc.get("server_powers", {}),
            "server_volume_flow_rates": bc.get("server_volume_flow_rates", {}),
            "supply_air_temperatures": bc.get("supply_air_temperatures", {}),
            "supply_air_volume_flow_rates": bc.get("supply_air_volume_flow_rates", {}),
        },
        "servers": len(pw),
        "total_kW": round(sum(pw) / 1000.0, 1),
        "mean_power_W": round(statistics.mean(pw), 1),
        "mean_dT_K": round(statistics.mean(dt), 2),
        "acu_T_C": round(statistics.mean(t), 2) if t else None,
    }


def main():
    cases = sorted((d for d in os.listdir(SRC) if d.startswith("case")),
                   key=lambda x: int(x[4:]) if x[4:].isdigit() else 1 << 30)
    rows = []
    for c in cases[:120]:                      # scan a slice; enough to spread on load
        s = summarise(c)
        if s and s["servers"] >= 300:          # full-room cases only
            rows.append(s)
    if not rows:
        raise SystemExit("no usable cases found")
    rows.sort(key=lambda r: r["total_kW"])
    # Spread evenly across the load range so the picks look different on screen.
    idx = [round(i * (len(rows) - 1) / (N_PICK - 1)) for i in range(N_PICK)]
    picked = [rows[i] for i in sorted(set(idx))]

    lines = ['// GENERATED by scripts/gen_scenarios.py — do not edit by hand.',
             '//',
             '// Demo operating points, taken from the dataset so their t=1 boundary field is',
             '// training-consistent and needs no solver run. Spread across total IT load so',
             '// consecutive picks look different in the viewport.',
             '',
             'export type ScenarioBc = {',
             '  server_powers: Record<string, number>;',
             '  server_volume_flow_rates: Record<string, number>;',
             '  supply_air_temperatures: Record<string, number>;',
             '  supply_air_volume_flow_rates: Record<string, number>;',
             '};',
             '',
             'export type Scenario = {',
             '  case: string; label: string; totalKW: number;',
             '  meanPowerW: number; meanDeltaTK: number; acuTC: number | null;',
             '  bc: ScenarioBc;',
             '};',
             '',
             'export const SCENARIOS: Scenario[] = [']
    for i, r in enumerate(picked):
        lo = picked[0]["total_kW"]; hi = picked[-1]["total_kW"]
        frac = (r["total_kW"] - lo) / max(hi - lo, 1e-9)
        name = ("Light load" if frac < 0.2 else "Nominal" if frac < 0.45
                else "Busy" if frac < 0.7 else "High load" if frac < 0.9 else "Peak load")
        lines.append(
            f'  {{ case: "{r["case"]}", label: "{name} · {r["total_kW"]} kW", '
            f'totalKW: {r["total_kW"]}, meanPowerW: {r["mean_power_W"]}, '
            f'meanDeltaTK: {r["mean_dT_K"]}, acuTC: {r["acu_T_C"]},\n'
            f'    bc: {json.dumps(r["bc"], separators=(",", ":"))} }},')
    lines += ['];', '']
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}")
    for r in picked:
        print(f"  {r['case']:8s} {r['total_kW']:7.1f} kW  meanP={r['mean_power_W']:7.1f} W  "
              f"meandT={r['mean_dT_K']:5.2f} K  ACU={r['acu_T_C']}")


if __name__ == "__main__":
    main()
