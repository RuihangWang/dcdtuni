#!/usr/bin/env bash
# Pack everything the demo needs that git does NOT carry, for transfer to another server.
#
# The code all lives in the repo and arrives by `git clone`. What does not is ~1.5 GB of
# binary assets: the GTC scene geometry, the pre-baked volume, the model checkpoint, and
# the base dataset case. This script collects exactly those, skipping the parts that are
# either rebuildable on the far end (kit-cae itself, node_modules) or dead weight
# (superseded .vtu revisions, dataset directories the demo never reads).
#
#   scripts/pack_deploy_bundle.sh                # dry run: list contents + total size
#   scripts/pack_deploy_bundle.sh /path/out.tar.zst   # write the archive
#
# See DEPLOY.md for what to do with the result on the receiving machine.
set -euo pipefail

DEMO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROOT="$(cd "$DEMO/../../../.." && pwd)"
REF="$ROOT/src/backend/kit-cae"
CASE0="${DC_CFD_GTC_DATASET:-/mnt/lv/home/Public/GTC/processed_dataset_unconverged}/case0"
OUT="${1:-}"

# Each entry: <label>|<absolute source>|<path inside the archive>
# Paths inside the archive are relative to the repo root so the far end can untar over a
# fresh clone without moving anything by hand.
ITEMS=(
  "GTC scene geometry (USDZ + textures)|$REF/data/GTC|src/backend/kit-cae/data/GTC"
  "pre-baked CFD volume|$DEMO/data/internal.vtu|src/frontend/omniverse/cfd_demo/data/internal.vtu"
  "colormap ranges|$DEMO/data/ranges.json|src/frontend/omniverse/cfd_demo/data/ranges.json"
  "SCANO checkpoint|$DEMO/SCANO/GTC_A3_Numerical/logger/model/best.state|src/frontend/omniverse/cfd_demo/SCANO/GTC_A3_Numerical/logger/model/best.state"
)

# The base dataset case is 939 MB whole, but the demo only reads these. VTK/ (155 MB),
# 500/ (52 MB) and _1_bak/ (46 MB) are training-era leftovers that nothing here opens.
CASE0_KEEP=(model.json boundary_conditions.json constant system 0 1 h5)

echo "=== bundle contents ==="
total=0
for e in "${ITEMS[@]}"; do
    IFS='|' read -r label src _ <<<"$e"
    if [ ! -e "$src" ]; then
        printf "  MISSING  %-36s %s\n" "$label" "$src"
        continue
    fi
    kb=$(du -sk "$src" | cut -f1); total=$((total + kb))
    printf "  %-36s %8s  %s\n" "$label" "$(du -sh "$src" | cut -f1)" "${src#$ROOT/}"
done
for d in "${CASE0_KEEP[@]}"; do
    [ -e "$CASE0/$d" ] || { printf "  MISSING  case0/%s\n" "$d"; continue; }
    kb=$(du -sk "$CASE0/$d" | cut -f1); total=$((total + kb))
    printf "  %-36s %8s  %s\n" "base case: case0/$d" "$(du -sh "$CASE0/$d" | cut -f1)" "(dataset)"
done
printf "\n  total (uncompressed): %s MB\n\n" "$((total / 1024))"

if [ -z "$OUT" ]; then
    cat <<'EOF'
NOT rebuildable on the far end, so all of the above must travel:
  - GTC/ is this project's own asset. `git ls-files data/GTC` in the kit-cae clone
    returns nothing, i.e. it is NOT part of NVIDIA's public repo.
  - best.state is trained weights.
  - internal.vtu can in principle be regenerated by convert_gtc_cfd.sh, but only from a
    full solved OpenFOAM case, which is far larger than the .vtu itself.

Deliberately NOT included (rebuild on the far end instead):
  - kit-cae itself, 7.3 GB   -> git clone --branch v2.0.1 https://github.com/NVIDIA-Omniverse/kit-cae.git && ./repo.sh build
  - kit_cae_user_guide_data  -> NVIDIA's public download (supplies GB300.usd)
  - web/node_modules, 105 MB -> npm install
  - internal.vtu.bak / .umag_real, 333 MB -> superseded revisions
  - case0/VTK, 500, _1_bak, 253 MB        -> never read by the demo

Re-run with an output path to write the archive:
  scripts/pack_deploy_bundle.sh ~/gtc_demo_assets.tar.zst
EOF
    exit 0
fi

# --transform rewrites each source to its repo-relative destination, so the receiving side
# untars at the repo root and every file lands where start_demo.sh already looks for it.
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
stage="$tmp/bundle"
for e in "${ITEMS[@]}"; do
    IFS='|' read -r _ src dst <<<"$e"
    [ -e "$src" ] || continue
    mkdir -p "$stage/$(dirname "$dst")"
    cp -a "$src" "$stage/$dst"
done
d0="$stage/src/frontend/omniverse/cfd_demo/SCANO/GTC_A3_Numerical/dataset/case0"
mkdir -p "$d0"
for d in "${CASE0_KEEP[@]}"; do
    [ -e "$CASE0/$d" ] && cp -aL "$CASE0/$d" "$d0/$d"
done

echo "[pack] compressing -> $OUT"
if command -v zstd >/dev/null 2>&1; then
    tar -C "$stage" -cf - . | zstd -T0 -3 -o "$OUT"
else
    echo "[pack] zstd not found, falling back to gzip (slower, larger)"
    tar -C "$stage" -czf "$OUT" .
fi
echo "[pack] done: $(du -sh "$OUT" | cut -f1)  $OUT"
