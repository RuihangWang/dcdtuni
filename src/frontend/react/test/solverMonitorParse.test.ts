import { readFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import {
  absorbProbeSample,
  emptyMonitorData,
  parseSolverLogLine,
  type ParseOutcome,
} from '../src/run/solverMonitorParse'

/**
 * The fixture is REAL solver output.
 *
 * `test/__fixtures__/solver_log_steady.txt` is lines 318-361 of
 * `case/GTC/log/2026-08-18-05-12-49_GTC/2026-08-18-05-12-49_GTC.log` — four
 * iterations of buoyantBoussinesqSimpleFoam as the server actually streamed
 * them, loguru prefix included. An invented log is where a parser passes its
 * own tests and finds nothing in production: the `|  INFO  |` prefix alone
 * breaks every anchored regex, and no hand-written sample has it by accident.
 */
const FIXTURES = resolve(process.cwd(), 'test/__fixtures__')
const LOG = readFileSync(join(FIXTURES, 'solver_log_steady.txt'), 'utf8')
  .split('\n')
  .filter((l) => l.trim().length > 0)

function feed(lines: string[]) {
  const data = emptyMonitorData()
  const outcomes: ParseOutcome[] = []
  for (const line of lines) outcomes.push(parseSolverLogLine(data, line))
  return { data, outcomes }
}

describe('parseSolverLogLine on a real steady solve', () => {
  it('finds the fixture', () => {
    expect(LOG.length).toBe(44)
  })

  it('collects one point per field per iteration', () => {
    const { data } = feed(LOG)
    expect(Object.keys(data.residuals).sort()).toEqual([
      'T',
      'Ux',
      'Uy',
      'Uz',
      'epsilon',
      'k',
      'p_rgh',
    ])
    for (const series of Object.values(data.residuals)) {
      expect(series.map((p) => p.step)).toEqual([1, 2, 3, 4])
    }
  })

  it('plots the INITIAL residual, not the final one', () => {
    // The initial residual is the error the iteration started from — the
    // convergence measure. The final one describes the linear solve inside the
    // step and falls to 1e-3 on iteration 1 of a diverging run.
    const { data } = feed(LOG)
    expect(data.residuals.Ux?.map((p) => p.value)).toEqual([1, 0.778485, 0.209146, 0.207604])
    expect(data.residuals.p_rgh?.map((p) => p.value)).toEqual([
      1, 0.239281, 0.316027, 0.269188,
    ])
  })

  it('does not read "ExecutionTime = 3.77" as a new time step', () => {
    // `\bTime` has no word boundary inside "ExecutionTime", which is the only
    // thing stopping the x axis from jumping to 3.77 s at the end of every
    // iteration.
    const { data } = feed(LOG)
    expect(data.currentStep).toBe(4)
  })

  it('asks for a redraw at each step boundary and each ExecutionTime', () => {
    const { outcomes } = feed(LOG)
    // 4 ExecutionTime lines + the 3 `Time =` lines that follow a step already
    // holding data. The first `Time = 1` has nothing to draw yet.
    expect(outcomes.filter((o) => o === 'redraw').length).toBe(7)
    expect(outcomes[0]).toBe('none')
    expect(outcomes[10]).toBe('redraw')
    expect(outcomes[11]).toBe('redraw')
  })

  it('ignores the continuity-error line, which also says "sum local ="', () => {
    const { data } = feed(LOG)
    expect(Object.keys(data.temperatures)).toEqual([])
  })

  it('keeps only the first residual of a field within one step', () => {
    // A PIMPLE outer corrector loop solves Ux several times per step; the extra
    // points would land on the same x and fold the curve back on itself.
    const { data } = feed([
      '2026-08-18 05:13:37 | INFO     | Time = 1',
      '2026-08-18 05:13:37 | INFO     | DILUPBiCGStab:  Solving for Ux, Initial residual = 0.5, Final residual = 0.01, No Iterations 1',
      '2026-08-18 05:13:37 | INFO     | DILUPBiCGStab:  Solving for Ux, Initial residual = 0.2, Final residual = 0.005, No Iterations 1',
    ])
    expect(data.residuals.Ux).toEqual([{ step: 1, value: 0.5 }])
  })

  it('reads a transient fractional time step', () => {
    const { data } = feed([
      '2026-08-18 05:13:37 | INFO     | Time = 0.001',
      '2026-08-18 05:13:37 | INFO     | DILUPBiCGStab:  Solving for T, Initial residual = 0.3, Final residual = 0.01, No Iterations 1',
    ])
    expect(data.residuals.T).toEqual([{ step: 0.001, value: 0.3 }])
  })
})

describe('surfaceFieldValue two-line state machine', () => {
  // The function object is generated by `generate_control_dict`
  // (openfoam_case.py:153) as `avgT_<patch>` with `log true`, so OpenFOAM prints
  // the banner on one line and the value on the next.
  const CURRENT = [
    '2026-08-18 05:13:37 | INFO     | surfaceFieldValue avgT_ACU1_return write:',
    '2026-08-18 05:13:37 | INFO     |     areaAverage(ACU1_return) of T = 300.125',
  ]
  const LEGACY_FORMAT = [
    '2026-08-18 05:13:37 | INFO     | avgT_rack1_front output:',
    '2026-08-18 05:13:37 | INFO     |     areaAverage(T) = 295',
  ]

  it('records the patch average against the current step', () => {
    const { data } = feed(['... | INFO     | Time = 12', ...CURRENT])
    expect(data.temperatures.avgT_ACU1_return).toEqual([{ step: 12, value: 300.125 }])
  })

  it('still reads the older "output:" banner and bare areaAverage(T)', () => {
    const { data } = feed(['... | INFO     | Time = 3', ...LEGACY_FORMAT])
    expect(data.temperatures.avgT_rack1_front).toEqual([{ step: 3, value: 295 }])
  })

  it('drops the expectation when the next line is not a value', () => {
    // Otherwise the banner would latch and attach a much later areaAverage to
    // the wrong function object.
    const { data } = feed([
      '... | INFO     | Time = 3',
      CURRENT[0] as string,
      '... | INFO     | something else entirely',
      '... | INFO     |     areaAverage(other) of T = 999',
    ])
    expect(data.temperatures).toEqual({})
  })

  it('asks the sensor poller to fetch when the probes function object writes', () => {
    const { outcomes } = feed(['2026-08-18 05:13:37 | INFO     | writing probe data'])
    expect(outcomes).toEqual(['probe-poll'])
  })
})

describe('absorbProbeSample', () => {
  it('indexes fields.T by [step][probe] in the order names were asked for', () => {
    const data = emptyMonitorData()
    const since = absorbProbeSample(
      data,
      ['inlet', 'outlet'],
      { steps: [10, 20], fields: { T: [[300, 310], [301, 311]] } },
      0,
    )
    expect(since).toBe(20)
    expect(data.sensors.inlet).toEqual([
      { step: 10, value: 300 },
      { step: 20, value: 301 },
    ])
    expect(data.sensors.outlet).toEqual([
      { step: 10, value: 310 },
      { step: 20, value: 311 },
    ])
  })

  it('marks a probe outside the mesh instead of plotting -1e300', () => {
    // OpenFOAM writes its "no cell here" sentinel as a huge negative number;
    // plotting it drags the y axis down by 300 orders of magnitude and flattens
    // every real curve into one line.
    const data = emptyMonitorData()
    absorbProbeSample(data, ['ghost'], { steps: [5], fields: { T: [[-1e300]] } }, 0)
    expect(data.sensors.ghost).toBeUndefined()
    expect(data.sensorNotFound.ghost).toBe(true)
  })
})
