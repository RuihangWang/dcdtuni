test('all five real cases migrate clean (invariants)', () => {
  const cases = [
    ['../../../case/Base_leakage/Base_leakage.cfdproj', { rack: 4, acu: 2, baffle: 3, wall: 4, floor: 3 }],
    ['../../../case/Shinaide/Shinaide.cfdproj', { rack: 14, acu: 4, box: 2, baffle: 3, floor: 2, wall: 4 }],
    ['../../../case/CMI-China/CMI_China.cfdproj', { rack: 20, acu: 4, box: 4, baffle: 3, floor: 2, wall: 4 }],
    ['../../../case/STDCT/STDCT.cfdproj', { rack: 24, acu: 3, box: 3, baffle: 7, floor: 3, wall: 4 }],
    ['../../../case/Liquid/Liquid.cfdproj', { rack: 4, cdu: 1, pipe_segment: 2, wall: 4, floor: 2 }],
  ];
  for (const [rel, kinds] of cases) {
    const raw = JSON.parse(readFileSync(new URL(rel, import.meta.url), 'utf8'));
    // P4 T7 converted the tracked case files to schemaVersion 4, so the on-disk
    // input may already be V4 (no `construction` array). The migrator is
    // idempotent, so derive the count/id invariants from whichever shape the
    // file carries — v3 `construction[]` if present, else the V4 buckets.
    const v4 = M.migrateCfdprojV3toV4(raw);
    assert.deepEqual(S.validateDocument(v4), [], rel);
    const buckets = v4.constructions;
    const isV3 = Array.isArray(raw.construction);
    // liquidFlowNetworks are DERIVED from liquidCooling.piping (not a 1:1 image of
    // construction[]), so they are excluded from the construction-count and
    // v3-id-membership invariants. Enabled-liquid cases (Liquid) legitimately add
    // a net_main entry that has no corresponding v3 construction id.
    const consBuckets = S.BUCKETS.filter(b => b !== 'liquidFlowNetworks');
    let migrated = 0;
    for (const b of consBuckets) migrated += Object.keys(buckets[b] || {}).length;
    const total = isV3
      ? raw.construction.length
      : consBuckets.reduce((n, b) => n + Object.keys((raw.constructions || {})[b] || {}).length, 0);
    assert.equal(migrated, total, rel + ': construction count preserved');
    for (const [kind, n] of Object.entries(kinds)) {
      const bucket = S.BUCKET_BY_KIND[kind];
      const got = Object.values(buckets[bucket]).filter(o => (o.meta && o.meta.legacyKind) ? o.meta.legacyKind === kind : true).length;
      assert.ok(got >= n, `${rel}: expected >= ${n} ${kind} in ${bucket}, got ${got}`);
    }
    const sourceIds = isV3
      ? new Set(raw.construction.map(m => m.id))
      : new Set(consBuckets.flatMap(b => Object.keys((raw.constructions || {})[b] || {})));
    for (const b of consBuckets) for (const uid of Object.keys(buckets[b] || {})) assert.ok(sourceIds.has(uid), uid);
    assert.deepEqual(M.migrateCfdprojV3toV4(v4), v4, rel + ': idempotent');
  }
});
