def noise2(rng, h, w, su, sv):
    """Periodic noise on an h x w tile; ``su``/``sv`` in cycles per tile along u/v."""
    white = rng.standard_normal((h, w))
    fx, fy = np.meshgrid(np.fft.fftfreq(w) * w, np.fft.fftfreq(h) * h)
    field = np.real(np.fft.ifft2(np.fft.fft2(white) * np.exp(-0.5 * ((fx / su) ** 2 + (fy / sv) ** 2))))
    field -= field.mean()
    std = field.std()
    return field / std if std > 0 else field


def mm_grid(h, w, width_mm, height_mm):
    """Pixel-centre coordinates in millimetres: x right, y UP (row 0 is the top)."""
    rows, cols = np.mgrid[0:h, 0:w].astype(float)
    return (cols + 0.5) / w * width_mm, (1.0 - (rows + 0.5) / h) * height_mm


def step(edge0, edge1, x):
    t = np.clip((x - edge0) / (edge1 - edge0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def inside(signed, soft):
    """1 where ``signed`` (mm, positive inside) is well inside, antialiased over ``soft`` mm."""
    return step(-soft, soft, signed)


def rect(x, y, x0, x1, y0, y1, soft):
    return inside(np.minimum(np.minimum(x - x0, x1 - x), np.minimum(y - y0, y1 - y)), soft)


def disc(x, y, cx, cy, r, soft):
    return inside(r - np.hypot(x - cx, y - cy), soft)


def stadium(x, y, cx, cy, half_len, r, soft):
    """A slot: a segment of half length ``half_len`` along x, radius ``r``."""
    dx = np.maximum(np.abs(x - cx) - half_len, 0.0)
    return inside(r - np.hypot(dx, y - cy), soft)


def hex_holes(x, y, pitch, radius, soft):
    """Pointy-top hexagonal holes on a staggered lattice: 1 inside a hole."""
    row_h = pitch * np.sqrt(3.0) / 2.0
    best = np.full(x.shape, np.inf)
    r0 = np.floor(y / row_h)
    for dr in (-1.0, 0.0, 1.0):
        r = r0 + dr
        off = np.where(np.mod(r, 2.0) == 1.0, pitch / 2.0, 0.0)
        cx = np.round((x - off) / pitch) * pitch + off
        cy = r * row_h
        dx = np.abs(x - cx)
        dy = np.abs(y - cy)
        d = np.maximum(dx, dx * 0.5 + dy * np.sqrt(3.0) / 2.0)
        best = np.minimum(best, d)
    return inside(radius - best, soft)


def round_holes(x, y, pitch, radius, soft, stagger=True):
    """Round holes on a (staggered) lattice: 1 inside a hole."""
    row_h = pitch * (np.sqrt(3.0) / 2.0 if stagger else 1.0)
    best = np.full(x.shape, np.inf)
    r0 = np.floor(y / row_h)
    for dr in (-1.0, 0.0, 1.0):
        r = r0 + dr
        off = np.where(np.mod(r, 2.0) == 1.0, pitch / 2.0, 0.0) if stagger else 0.0
        cx = np.round((x - off) / pitch) * pitch + off
        best = np.minimum(best, np.hypot(x - cx, y - r * row_h))
    return inside(radius - best, soft)


def blend(base, mask, value):
    return base * (1.0 - mask) + value * mask


def out(lum, height, tilt, rough, alpha=None, rgb=(1.0, 1.0, 1.0)):
    return {'color': tint(np.clip(lum, 0, 1), rgb), 'height': height, 'tilt': tilt, 'rough': rough, 'alpha': alpha}


