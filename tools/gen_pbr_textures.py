def _freqs(n: int):
    f = np.fft.fftfreq(n) * n  # integer cycles per tile
    return np.meshgrid(f, f)  # fx varies along columns (u), fy along rows (v)


def spectral_noise(rng, n=SIZE, sigma_u=8.0, sigma_v=8.0, beta=0.0):
    """Periodic Gaussian-filtered noise, normalised to zero mean / unit std.

    ``sigma_u``/``sigma_v`` are the filter widths in cycles per tile along
    u (columns) and v (rows): a small ``sigma_u`` with a large ``sigma_v`` is
    long along u and fine across it, i.e. streaks running along u.
    """
    white = rng.standard_normal((n, n))
    fx, fy = _freqs(n)
    filt = np.exp(-0.5 * ((fx / sigma_u) ** 2 + (fy / sigma_v) ** 2))
    if beta:
        r = np.sqrt(fx ** 2 + fy ** 2)
        r[0, 0] = 1.0
        filt = filt * r ** (-beta)
    field = np.real(np.fft.ifft2(np.fft.fft2(white) * filt))
    field -= field.mean()
    std = field.std()
    return field / std if std > 0 else field


def periodic_voronoi(rng, cells: int, n=SIZE):
    """Cell id and distance-to-edge proxy for a periodic Voronoi diagram."""
    pts = rng.random((cells, 2)) * n
    # 3x3 periodic copies so distances wrap across the tile edges
    offs = np.array([(dx, dy) for dx in (-n, 0, n) for dy in (-n, 0, n)], dtype=float)
    allp = (pts[None, :, :] + offs[:, None, :]).reshape(-1, 2)
    ids = np.tile(np.arange(cells), 9)
    ys, xs = np.mgrid[0:n, 0:n].astype(float)
    cell = np.zeros((n, n), dtype=int)
    edge = np.zeros((n, n))
    for r0 in range(0, n, 32):
        px = xs[r0:r0 + 32, :, None]
        py = ys[r0:r0 + 32, :, None]
        d2 = (px - allp[None, None, :, 0]) ** 2 + (py - allp[None, None, :, 1]) ** 2
        order = np.argpartition(d2, 1, axis=2)[..., :2]
        d_sorted = np.take_along_axis(d2, order, axis=2)
        swap = d_sorted[..., 0] > d_sorted[..., 1]
        first = np.where(swap, order[..., 1], order[..., 0])
        cell[r0:r0 + 32] = ids[first]
        d1 = np.sqrt(np.minimum(d_sorted[..., 0], d_sorted[..., 1]))
        d2b = np.sqrt(np.maximum(d_sorted[..., 0], d_sorted[..., 1]))
        edge[r0:r0 + 32] = d2b - d1
    return cell, edge


def normal_from_height(h, rms_tilt: float):
    """OpenGL tangent-space normal map from a height field (row 0 = top = +v).

    The slope is rescaled so its RMS equals ``rms_tilt`` (tan of the mean
    tilt): the height fields mix octaves freely, and without a fixed slope
    budget a fine-grain octave turns the map into per-pixel noise that neither
    reads as a surface nor compresses.
    """
    dhdu = (np.roll(h, -1, axis=1) - np.roll(h, 1, axis=1)) * 0.5
    dhdv = (np.roll(h, 1, axis=0) - np.roll(h, -1, axis=0)) * 0.5  # v grows upward
    rms = float(np.sqrt(np.mean(dhdu * dhdu + dhdv * dhdv))) or 1.0
    nx = -(rms_tilt / rms) * dhdu
    ny = -(rms_tilt / rms) * dhdv
    nz = np.ones_like(h)
    inv = 1.0 / np.sqrt(nx * nx + ny * ny + nz * nz)
    rgb = np.stack([nx * inv, ny * inv, nz * inv], axis=-1)
    return np.clip((rgb * 0.5 + 0.5) * 255.0 + 0.5, 0, 255).astype(np.uint8)


def to_u8(x):
    return np.clip(x * 255.0 + 0.5, 0, 255).astype(np.uint8)


def tint(gray, rgb):
    """Gray in [0,1] times an sRGB colour triplet -> HxWx3 floats."""
    return np.clip(gray[..., None] * np.asarray(rgb, dtype=float)[None, None, :], 0, 1)


