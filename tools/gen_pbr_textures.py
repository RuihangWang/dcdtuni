def _src(entry) -> str:
    s = entry['source']
    if s['kind'] == 'generated':
        return f"generated (`{s['recipe']}`, seed {s['seed']}), project-owned, CC0"
    if s['kind'] == 'photo':
        return f"[{s['origin']}]({s['url']}), {s['license']}" + (f" — {s['notes']}" if s.get('notes') else '')
    return f"{s['origin']}, {s['license']}" + (f" — {s['notes']}" if s.get('notes') else '')


def credits_block(manifest) -> str:
    users = {}
    for kind, mat in manifest['materials'].items():
        if mat.get('set'):
            users.setdefault(mat['set'], []).append(kind)
    lines = [CREDITS_BEGIN,
             '## Pool contents (generated from materials.json)',
             '',
             'Every image below is listed in `materials.json` with its size, byte count and',
             'sha256 (= its Git LFS oid). Generated sets are rebuilt bit for bit by',
             '`python3 tools/gen_pbr_textures.py --check`.',
             '',
             '### Texture sets',
             '',
             '| Set | Size | Source | Tintable | Median luminance | Mean roughness | Materials |',
             '|-----|------|--------|----------|------------------|----------------|-----------|']
    for name, s in manifest['sets'].items():
        size = 'x'.join(str(v) for v in s['maps']['color']['size'])
        lines.append(f"| {name}/ | {size} | {_src(s)} | {'yes' if s['tintable'] else 'no'} | "
                     f"{s['stats']['medianLuminance']:.3f} | {s['stats']['meanRoughness']:.3f} | "
                     f"{', '.join(sorted(users.get(name, []))) or '—'} |")
    lines += ['', '### Single images', '', '| File | Size | Source | Use |', '|------|------|--------|-----|']
    for pid, p in manifest['photos'].items():
        lines.append(f"| {p['image']['file']} | {'x'.join(str(v) for v in p['image']['size'])} | {_src(p)} | {p['label']} |")
    for p in manifest['patchPresets']:
        lines.append(f"| {p['image']['file']} | {'x'.join(str(v) for v in p['image']['size'])} | {_src(p)} | "
                     f"patch preset `{p['id']}` ({', '.join(p['roles'])}) |")
    lines.append(CREDITS_END)
    return '\n'.join(lines)


def credits_text(current: str, manifest) -> str:
    block = credits_block(manifest)
    if CREDITS_BEGIN in current:
        head = current.split(CREDITS_BEGIN)[0]
        tail = current.split(CREDITS_END, 1)[1]
        return head + block + tail
    return current.rstrip('\n') + '\n\n' + block + '\n'


# ---------------------------------------------------------------------------

def build(pool: Path):
    manifest = json.loads((pool / MANIFEST).read_text())
    if manifest.get('schema') != 'dcdtuni.material-library/v1':
        raise SystemExit(f'{MANIFEST}: unexpected schema {manifest.get("schema")!r}')
    generated: dict[str, bytes] = {}
    for name, entry in manifest['sets'].items():
        if entry['source']['kind'] == 'generated':
            files = build_generated(entry)
            for rel in files:
                if not rel.startswith(name + '/'):
                    raise SystemExit(f'{rel}: a generated set writes inside its own folder {name}/')
            generated.update(files)
    update_manifest(manifest, pool, generated)
    return manifest, generated


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true',
                    help='regenerate in memory and verify every generated file, the manifest and CREDITS are byte-identical')
    args = ap.parse_args(argv)
    manifest, generated = build(TEXTURES)
    text = dumps(manifest)
    credits = credits_text((TEXTURES / 'CREDITS.md').read_text(), manifest)
    unreferenced = sorted(pool_images(TEXTURES) - referenced(manifest) - set(generated))
    if args.check:
        bad = []
        with tempfile.TemporaryDirectory() as tmp:
            for rel, data in generated.items():
                (Path(tmp) / rel).parent.mkdir(parents=True, exist_ok=True)
                (Path(tmp) / rel).write_bytes(data)
                repo = TEXTURES / rel
                if not repo.is_file() or repo.read_bytes() != data:
                    bad.append(rel)
        if (TEXTURES / MANIFEST).read_text() != text:
            bad.append(MANIFEST + ' (measured fields differ from the files)')
        if (TEXTURES / 'CREDITS.md').read_text() != credits:
            bad.append('CREDITS.md (generated section is stale)')
        bad += [f'{rel} (in the pool, not in the manifest)' for rel in unreferenced]
        if bad:
            print('MISMATCH:\n  ' + '\n  '.join(bad))
            return 1
        print(f'OK: {len(generated)} generated files, the manifest and CREDITS are byte-identical')
        return 0
    for rel, data in generated.items():
        (TEXTURES / rel).parent.mkdir(parents=True, exist_ok=True)
        (TEXTURES / rel).write_bytes(data)
    (TEXTURES / MANIFEST).write_text(text)
    (TEXTURES / 'CREDITS.md').write_text(credits)
    for name, e in manifest['sets'].items():
        kb = sum(m['bytes'] for m in e['maps'].values()) / 1024
        print(f"{name:20s} {e['source']['kind']:9s} {'x'.join(map(str, e['maps']['color']['size'])):>9s} "
              f"median-lum={e['stats']['medianLuminance']:.3f} rough={e['stats']['meanRoughness']:.3f} {kb:6.0f} KB")
    if unreferenced:
        print('WARNING: pool images the manifest does not reference:\n  ' + '\n  '.join(unreferenced))
    return 0


if __name__ == '__main__':
    sys.exit(main())
