def brushed_stainless(rng):
    streak = spectral_noise(rng, sigma_u=2.0, sigma_v=120.0)       # long along u
    fine = spectral_noise(rng, sigma_u=6.0, sigma_v=200.0)
    blotch = spectral_noise(rng, sigma_u=3.0, sigma_v=3.0)
    lum = 0.90 + 0.035 * streak + 0.015 * fine + 0.012 * blotch
    color = tint(lum, (1.0, 1.0, 1.0))
    height = 0.8 * streak + 0.4 * fine
    rough = 0.34 + 0.05 * streak + 0.03 * blotch
    return color, height, 0.10, rough


def copper(rng):
    streak = spectral_noise(rng, sigma_u=3.0, sigma_v=90.0)
    blotch = spectral_noise(rng, sigma_u=4.0, sigma_v=4.0)
    tarnish = np.clip(spectral_noise(rng, sigma_u=3.0, sigma_v=3.0) - 1.3, 0, None)
    lum = 0.92 + 0.03 * streak + 0.02 * blotch - 0.05 * tarnish
    base = np.array((0.86, 0.53, 0.38))
    dark = np.array((0.62, 0.36, 0.27))
    mix = np.clip(tarnish * 0.35, 0, 1)[..., None]
    color = np.clip(lum[..., None] * (base * (1 - mix) + dark * mix), 0, 1)
    height = 0.7 * streak + 0.3 * blotch
    rough = 0.30 + 0.04 * streak + 0.06 * tarnish
    return color, height, 0.08, rough


def painted_steel(rng):
    peel = spectral_noise(rng, sigma_u=28.0, sigma_v=28.0)          # orange peel
    speck = spectral_noise(rng, sigma_u=160.0, sigma_v=160.0)
    cloud = spectral_noise(rng, sigma_u=2.0, sigma_v=2.0)
    lum = 0.90 + 0.012 * cloud + 0.010 * speck
    color = tint(lum, (1.0, 1.0, 1.0))
    height = peel + 0.15 * speck
    rough = 0.55 + 0.04 * peel + 0.02 * cloud
    return color, height, 0.06, rough


def pipe_insulation(rng):
    # Closed-cell elastomeric foam: fine cellular dimples plus the faint
    # extrusion lines that run along the pipe (u is along the pipe).
    cells = spectral_noise(rng, sigma_u=32.0, sigma_v=32.0)
    pits = np.clip(-spectral_noise(rng, sigma_u=45.0, sigma_v=45.0) - 1.8, 0, None)
    extr = spectral_noise(rng, sigma_u=1.5, sigma_v=60.0)
    cloud = spectral_noise(rng, sigma_u=2.0, sigma_v=2.0)
    lum = 0.89 + 0.015 * cloud + 0.012 * cells - 0.05 * pits
    color = tint(lum, (1.0, 1.0, 1.0))
    height = 0.6 * cells - 1.2 * pits + 0.25 * extr
    rough = 0.82 + 0.04 * cells + 0.05 * pits
    return color, height, 0.12, rough


def galvanized_steel(rng):
    cell, edge = periodic_voronoi(rng, cells=46)
    shade = rng.random(cell.max() + 1)[cell]                         # spangle facets
    grain = spectral_noise(rng, sigma_u=60.0, sigma_v=60.0)
    cloud = spectral_noise(rng, sigma_u=2.5, sigma_v=2.5)
    rim = np.exp(-edge / 1.5)
    lum = 0.86 + 0.06 * (shade - 0.5) + 0.010 * grain + 0.012 * cloud - 0.03 * rim
    color = tint(lum, (1.0, 1.0, 1.0))
    height = 0.6 * (shade - 0.5) + 0.2 * grain - 0.5 * rim
    rough = 0.42 + 0.10 * (shade - 0.5) + 0.03 * cloud
    return color, height, 0.07, rough


