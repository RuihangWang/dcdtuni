def server_bezel(rng, w, h):
    """One rack unit of a server front (stretched across the face, one tile per U).

    Nominal 440 x 44.45 mm: rack ears with handles, four drive bays, a
    honeycomb intake grille and two status lamps. High-key neutral metal, so the
    server's colour decides the hue; the holes stay dark whatever it is.
    """
    x, y = mm_grid(h, w, 440.0, 44.45)
    s = 0.45
    lum = 0.86 + 0.010 * noise2(rng, h, w, 40, 4) + 0.006 * noise2(rng, h, w, 3, 1)
    height = np.zeros_like(x)
    rough = 0.52 + 0.03 * noise2(rng, h, w, 30, 3)
    seam = 1.0 - step(0.35, 0.9, np.minimum(y, 44.45 - y))           # gap to the unit above/below
    for x0, x1 in ((0.0, 21.0), (419.0, 440.0)):                     # rack ears
        ear = rect(x, y, x0, x1, 1.0, 43.45, s)
        lum = blend(lum, ear, 0.90)
        height += 0.5 * ear
    for cx in (12.0, 428.0):                                          # handles
        handle = stadium(np.zeros_like(x) + y, x, 22.2, cx, 13.0, 2.6, s)
        lum = blend(lum, handle, 0.95)
        rough = blend(rough, handle, 0.30)
        height += 1.2 * handle
    for cx in (5.0, 435.0):                                           # thumb screws
        screw = disc(x, y, cx, 22.2, 2.0, s)
        lum = blend(lum, screw, 0.60)
        height += 0.6 * screw
    for i in range(4):                                                # drive bays
        bx0 = 28.0 + i * 40.0
        bay = rect(x, y, bx0, bx0 + 38.0, 4.0, 40.45, s)
        edge = bay - rect(x, y, bx0 + 0.9, bx0 + 37.1, 4.9, 39.55, s)
        lum = blend(lum, edge, 0.25)
        height -= 0.8 * edge
        vent = rect(x, y, bx0 + 4.0, bx0 + 34.0, 18.0, 33.0, s) * hex_holes(x, y, 2.4, 0.75, 0.25)
        lum = blend(lum, vent, 0.08)
        height -= vent
        latch = rect(x, y, bx0 + 3.0, bx0 + 35.0, 6.0, 11.0, s)
        lum = blend(lum, latch, 0.93)
        height += 0.5 * latch
        led = disc(x, y, bx0 + 33.0, 36.5, 0.9, 0.3)
        lum = blend(lum, led, 0.55)
    grille = rect(x, y, 196.0, 404.0, 6.0, 38.45, s)
    holes = grille * hex_holes(x, y, 4.2, 1.6, 0.3)
    frame = grille - rect(x, y, 197.2, 402.8, 7.2, 37.25, s)
    lum = blend(lum, frame, 0.70)
    lum = blend(lum, holes, 0.06)
    height -= 1.0 * holes + 0.3 * frame
    rough = blend(rough, holes, 0.95)
    for cy in (33.0, 26.0):                                           # status lamps
        lamp = disc(x, y, 410.5, cy, 1.1, 0.3)
        lum = blend(lum, lamp, 0.75)
        height += 0.4 * lamp
    lum = blend(lum, seam, 0.18)
    height -= 1.2 * seam
    rough = blend(rough, seam, 0.9)
    return out(lum, height, 0.18, rough)


def server_rear(rng, w, h):
    """One rack unit of a server rear: honeycomb exhaust, I/O ports, two power supplies."""
    x, y = mm_grid(h, w, 440.0, 44.45)
    s = 0.45
    lum = 0.87 + 0.012 * noise2(rng, h, w, 50, 5) + 0.006 * noise2(rng, h, w, 3, 1)
    height = np.zeros_like(x)
    rough = 0.48 + 0.03 * noise2(rng, h, w, 30, 3)
    seam = 1.0 - step(0.35, 0.9, np.minimum(y, 44.45 - y))
    exhaust = rect(x, y, 6.0, 218.0, 5.0, 39.45, s)
    holes = exhaust * hex_holes(x, y, 3.6, 1.35, 0.3)
    lum = blend(lum, holes, 0.07)
    height -= holes
    rough = blend(rough, holes, 0.95)
    ports = [(226.0, 239.5, 17.0, 28.5), (242.0, 255.5, 17.0, 28.5),   # RJ45
             (261.0, 274.0, 10.0, 15.5), (261.0, 274.0, 19.0, 24.5),   # USB
             (279.0, 297.0, 28.0, 36.0), (279.0, 297.0, 10.0, 18.0)]   # serial / VGA
    for x0, x1, y0, y1 in ports:
        rim = rect(x, y, x0 - 0.8, x1 + 0.8, y0 - 0.8, y1 + 0.8, s)
        port = rect(x, y, x0, x1, y0, y1, s)
        lum = blend(lum, rim, 0.55)
        lum = blend(lum, port, 0.10)
        height -= 0.8 * port
        rough = blend(rough, port, 0.85)
    for i in range(2):                                                # power supplies
        px0 = 304.0 + i * 68.0
        psu = rect(x, y, px0, px0 + 66.0, 2.0, 42.45, s)
        gap = psu - rect(x, y, px0 + 0.9, px0 + 65.1, 2.9, 41.55, s)
        lum = blend(lum, gap, 0.20)
        height -= 0.8 * gap
        fan = disc(x, y, px0 + 18.0, 22.2, 15.0, s) * round_holes(x, y, 2.2, 0.75, 0.25)
        ring = disc(x, y, px0 + 18.0, 22.2, 16.0, s) - disc(x, y, px0 + 18.0, 22.2, 15.0, s)
        lum = blend(lum, ring, 0.65)
        lum = blend(lum, fan, 0.07)
        height -= fan - 0.4 * ring
        inlet = rect(x, y, px0 + 37.0, px0 + 55.0, 13.0, 31.5, s)
        lum = blend(lum, inlet, 0.09)
        height -= 0.9 * inlet
        for pin_x in (px0 + 42.0, px0 + 46.0, px0 + 50.0):
            pin = rect(x, y, pin_x - 0.8, pin_x + 0.8, 19.0, 25.5, 0.3) * inlet
            lum = blend(lum, pin, 0.35)
        handle = stadium(np.zeros_like(x) + y, x, 22.2, px0 + 61.0, 14.0, 1.8, s)
        lum = blend(lum, handle, 0.94)
        height += 1.0 * handle
        rough = blend(rough, handle, 0.32)
    lum = blend(lum, seam, 0.18)
    height -= 1.2 * seam
    rough = blend(rough, seam, 0.9)
    return out(lum, height, 0.18, rough)


def rack_rail(rng, w, h):
    """One rack unit of a 19-inch mounting rail: three EIA-310 square cage-nut holes."""
    x, y = mm_grid(h, w, 50.0, 44.45)
    s = 0.35
    lum = 0.86 + 0.012 * noise2(rng, h, w, 3, 30) + 0.006 * noise2(rng, h, w, 2, 2)
    height = np.zeros_like(x)
    rough = 0.50 + 0.03 * noise2(rng, h, w, 20, 20)
    for x0, x1 in ((0.0, 2.2), (47.8, 50.0)):                         # bent flanges
        bend = rect(x, y, x0 - 1.0, x1, -1.0, 46.0, s) if x0 == 0.0 else rect(x, y, x0, x1 + 1.0, -1.0, 46.0, s)
        lum = blend(lum, bend, 0.62)
        height -= 0.6 * bend
    for cy in (6.35, 22.225, 38.1):                                   # EIA-310 hole positions
        hole = rect(x, y, 25.0 - 4.75, 25.0 + 4.75, cy - 4.75, cy + 4.75, s)
        lip = rect(x, y, 25.0 - 5.5, 25.0 + 5.5, cy - 5.5, cy + 5.5, s) - hole
        lum = blend(lum, lip, 0.70)
        lum = blend(lum, hole, 0.05)
        height -= hole + 0.3 * lip
        rough = blend(rough, hole, 0.95)
    tick = rect(x, y, 4.0, 11.0, -0.4, 0.4, 0.3)                     # unit boundary mark
    lum = blend(lum, tick, 0.45)
    return out(lum, height, 0.15, rough)


def blanking_panel(rng, w, h):
    """Four rack units of snap-in blanking panel: moulded grain and a seam per unit."""
    x, y = mm_grid(h, w, 177.8, 177.8)
    lum = 0.88 + 0.012 * noise2(rng, h, w, 2, 90) + 0.008 * noise2(rng, h, w, 3, 3)
    height = 0.5 * noise2(rng, h, w, 2, 90) + 0.3 * noise2(rng, h, w, 120, 120)
    rough = 0.72 + 0.03 * noise2(rng, h, w, 40, 40)
    t = np.mod(y, 44.45)
    seam = 1.0 - step(0.25, 0.75, np.minimum(t, 44.45 - t))
    bevel = step(0.6, 1.0, t) * (1.0 - step(1.0, 1.8, t))
    lum = blend(lum, seam, 0.30)
    lum = lum + 0.04 * bevel
    height = height - 3.0 * seam + 0.8 * bevel
    rough = blend(rough, seam, 0.9)
    for cy in (22.225,):                                              # tool-less clip at each end
        for cx in (8.0, 169.8):
            clip = stadium(x, np.mod(y, 44.45), cx, cy, 2.5, 3.0, 0.3)
            lum = blend(lum, clip, 0.80)
            height += 0.8 * clip
    return out(lum, height, 0.10, rough)


def floor_tile(rng, w, h):
    """Four by four 600 mm anti-static HPL raised-floor tiles with seams and a slight tone per tile."""
    x, y = mm_grid(h, w, 2400.0, 2400.0)
    ix = np.floor(x / 600.0).astype(int) % 4
    iy = np.floor(y / 600.0).astype(int) % 4
    tone = rng.normal(0.0, 0.016, (4, 4))[iy, ix]
    chips_dark = np.clip(noise2(rng, h, w, 230, 230) - 1.7, 0, None)
    chips_light = np.clip(noise2(rng, h, w, 230, 230) - 1.9, 0, None)
    lum = 0.86 + tone + 0.008 * noise2(rng, h, w, 6, 6) - 0.10 * chips_dark + 0.05 * chips_light
    height = 0.2 * noise2(rng, h, w, 200, 200)
    rough = 0.58 + 0.03 * noise2(rng, h, w, 20, 20) + 0.05 * chips_dark
    dx = np.minimum(np.mod(x, 600.0), 600.0 - np.mod(x, 600.0))
    dy = np.minimum(np.mod(y, 600.0), 600.0 - np.mod(y, 600.0))
    d = np.minimum(dx, dy)
    # A 4 mm joint between tiles and a soft 10 mm edge bevel: wide enough to
    # survive mipmapping at room scale, where a 1 px line disappears.
    groove = 1.0 - step(2.0, 4.5, d)
    bevel = (1.0 - step(4.5, 12.0, d)) - groove
    lum = blend(lum, groove, 0.32) - 0.06 * bevel
    height = height - 3.0 * groove - 0.6 * bevel
    rough = blend(rough, groove, 0.9)
    return out(lum, height, 0.06, rough)


def floor_grate(rng, w, h):
    """One 600 mm perforated floor tile: hot-dip galvanized frame and bar grating over a dark plenum."""
    x, y = mm_grid(h, w, 600.0, 600.0)
    cell, _ = periodic_voronoi_rect(rng, 60, h, w)
    shade = rng.random(cell.max() + 1)[cell]
    lum = 0.74 + 0.05 * (shade - 0.5) + 0.01 * noise2(rng, h, w, 40, 40)
    height = 0.3 * (shade - 0.5)
    rough = 0.44 + 0.08 * (shade - 0.5)
    inner = rect(x, y, 25.0, 575.0, 25.0, 575.0, 0.6)
    pitch = 27.5
    gx = np.mod(x - 25.0, pitch)
    gy = np.mod(y - 25.0, pitch)
    bar = 10.0                                                        # 17.5 mm openings, 40 % open
    opening = inner * inside(np.minimum(np.minimum(gx - bar / 2, pitch - bar / 2 - gx),
                                        np.minimum(gy - bar / 2, pitch - bar / 2 - gy)), 0.6)
    lum = blend(lum, opening, 0.05)
    height -= 2.0 * opening
    rough = blend(rough, opening, 0.95)
    edge = np.minimum(np.minimum(x, 600.0 - x), np.minimum(y, 600.0 - y))
    joint = 1.0 - step(0.8, 2.2, edge)
    lum = blend(lum, joint, 0.30)
    height -= 1.5 * joint
    return out(lum, height, 0.10, rough)


def periodic_voronoi_rect(rng, cells, h, w):
    """Periodic Voronoi cell id on an h x w tile (galvanized spangle)."""
    pts = rng.random((cells, 2)) * np.array([w, h])
    offs = np.array([(dx, dy) for dx in (-w, 0, w) for dy in (-h, 0, h)], dtype=float)
    allp = (pts[None, :, :] + offs[:, None, :]).reshape(-1, 2)
    ids = np.tile(np.arange(cells), 9)
    ys, xs = np.mgrid[0:h, 0:w].astype(float)
    cell = np.zeros((h, w), dtype=int)
    for r0 in range(0, h, 32):
        d2 = (xs[r0:r0 + 32, :, None] - allp[None, None, :, 0]) ** 2 + (ys[r0:r0 + 32, :, None] - allp[None, None, :, 1]) ** 2
        cell[r0:r0 + 32] = ids[np.argmin(d2, axis=2)]
    return cell, None


def ceiling_tile(rng, w, h):
    """Two by two 600 mm mineral-fibre acoustic tiles in a white exposed T-bar grid."""
    x, y = mm_grid(h, w, 1200.0, 1200.0)
    pin = np.clip(noise2(rng, h, w, 300, 300) - 1.9, 0, None)
    worm = 1.0 - step(0.0, 0.08, np.abs(noise2(rng, h, w, 40, 70)))
    worm *= np.clip(noise2(rng, h, w, 6, 6) + 0.3, 0, 1)
    lum = 0.92 + 0.008 * noise2(rng, h, w, 4, 4) - 0.25 * pin - 0.08 * worm
    height = 0.4 * noise2(rng, h, w, 160, 160) - 2.0 * pin - 0.8 * worm
    rough = 0.94 + 0.02 * noise2(rng, h, w, 40, 40)
    dx = np.minimum(np.mod(x, 600.0), 600.0 - np.mod(x, 600.0))
    dy = np.minimum(np.mod(y, 600.0), 600.0 - np.mod(y, 600.0))
    d = np.minimum(dx, dy)
    bar = 1.0 - step(6.5, 8.0, d)
    reveal = (1.0 - step(8.0, 10.5, d)) - bar
    lum = blend(lum, bar, 0.97)
    lum = blend(lum, reveal, 0.70)
    height = blend(height, bar, 1.5) - 1.0 * reveal
    rough = blend(rough, bar, 0.42)
    return out(lum, height, 0.08, rough)


def wall_paint(rng, w, h):
    """Emulsion paint on plaster: a soft roller stipple and faint cloud, nothing else."""
    stipple = noise2(rng, h, w, 120, 120)
    micro = noise2(rng, h, w, 240, 240)
    cloud = noise2(rng, h, w, 3, 3)
    lum = 0.90 + 0.006 * stipple + 0.008 * cloud
    height = stipple + 0.3 * micro
    rough = 0.88 + 0.02 * stipple
    return out(lum, height, 0.05, rough)


def louvre(rng, w, h):
    """Supply louvre: eight angled aluminium blades per 150 mm tile, dark slots between."""
    x, y = mm_grid(h, w, 150.0, 150.0)
    pitch = 150.0 / 8.0
    t = np.mod(y, pitch) / pitch
    blade = step(0.16, 0.22, t)
    face = 0.72 + 0.25 * step(0.2, 1.0, t)
    lum = blend(np.full_like(x, 0.10), blade, face) + 0.008 * noise2(rng, h, w, 4, 30)
    height = blade * t * 3.0 - (1.0 - blade) * 1.0
    rough = blend(np.full_like(x, 0.9), blade, 0.40 + 0.03 * noise2(rng, h, w, 6, 40))
    return out(lum, height, 0.30, rough)


def perforated_sheet(rng, w, h):
    """Round-hole perforated steel sheet: 5 mm holes on an 8 mm staggered pitch (35 % open)."""
    # 20 pitches across; 12 row pairs (8 * sqrt(3) mm each) up, so the stagger tiles too.
    x, y = mm_grid(h, w, 160.0, 12 * 8.0 * np.sqrt(3.0))
    holes = round_holes(x, y, 8.0, 2.5, 0.25)
    lum = 0.86 + 0.012 * noise2(rng, h, w, 3, 3) + 0.008 * noise2(rng, h, w, 60, 60)
    lum = blend(lum, holes, 0.06)
    rim = round_holes(x, y, 8.0, 3.1, 0.25) - holes
    lum = blend(lum, rim, 0.78)
    height = 0.3 * noise2(rng, h, w, 60, 60) - 1.5 * holes - 0.4 * rim
    rough = blend(0.45 + 0.03 * noise2(rng, h, w, 20, 20), holes, 0.95)
    return out(lum, height, 0.12, rough)


def slotted_grille(rng, w, h):
    """Slotted return grille: staggered 28 x 7 mm slots in satin aluminium."""
    x, y = mm_grid(h, w, 300.0, 300.0)
    px, py = 37.5, 18.75
    row = np.floor(y / py)
    xs = x + np.where(np.mod(row, 2.0) == 1.0, px / 2.0, 0.0)
    cx = np.mod(xs, px) - px / 2.0
    cy = np.mod(y, py) - py / 2.0
    slot = stadium(cx, cy, 0.0, 0.0, 10.5, 3.5, 0.3)
    lum = 0.86 + 0.012 * noise2(rng, h, w, 3, 60) + 0.006 * noise2(rng, h, w, 3, 3)
    lum = blend(lum, slot, 0.06)
    height = 0.3 * noise2(rng, h, w, 3, 60) - 1.5 * slot
    rough = blend(0.42 + 0.03 * noise2(rng, h, w, 20, 20), slot, 0.95)
    return out(lum, height, 0.12, rough)


def containment_panel(rng, w, h):
    """Aisle-containment panel, stretched over the baffle: an aluminium frame round clear polycarbonate.

    The colour PNG carries alpha: opaque frame and gasket, a translucent sheet.
    """
    u = (np.arange(w) + 0.5) / w
    v = 1.0 - (np.arange(h) + 0.5) / h
    uu, vv = np.meshgrid(u, v)
    d = np.minimum(np.minimum(uu, 1.0 - uu), np.minimum(vv, 1.0 - vv))
    px = 1.0 / w
    frame = 1.0 - step(0.028 - px, 0.028 + px, d)
    gasket = (1.0 - step(0.034 - px, 0.034 + px, d)) - frame
    sheet = 1.0 - frame - gasket
    brushed = noise2(rng, h, w, 2, 160)
    scratches = np.clip(np.abs(noise2(rng, h, w, 3, 200)) - 2.4, 0, None)
    lum = blend(blend(0.97 + 0.01 * scratches, frame, 0.80 + 0.02 * brushed), gasket, 0.08)
    alpha = np.clip(blend(blend(0.30 + 0.04 * scratches, frame, 1.0), gasket, 1.0), 0, 1)
    bevel = (1.0 - step(0.0, 0.02, np.abs(d - 0.014))) * frame
    height = 1.5 * frame + 0.4 * bevel - 1.0 * gasket + 0.2 * brushed * frame
    rough = blend(blend(0.08 + 0.05 * scratches, frame, 0.42), gasket, 0.85)
    return out(lum, height, 0.10, rough, alpha=alpha)


