def _jpeg(img: Image.Image, **kw) -> bytes:
    buf = io.BytesIO()
    img.save(buf, 'JPEG', quality=JPEG_QUALITY, optimize=True, **kw)
    return buf.getvalue()


def _png(img: Image.Image) -> bytes:
    buf = io.BytesIO()
    img.save(buf, 'PNG', optimize=True)
    return buf.getvalue()


def build_generated(entry) -> dict[str, bytes]:
    """The set's map files, keyed by their pool-relative path."""
    src = entry['source']
    recipe = src['recipe']
    rng = np.random.default_rng(src['seed'])
    w, h = src['size']
    maps = entry['maps']
    if recipe in SQUARE_RECIPES:
        if [w, h] != [SIZE, SIZE]:
            raise SystemExit(f'{recipe} is a {SIZE}x{SIZE} recipe, the manifest asks for {w}x{h}')
        color, height, tilt, rough = SQUARE_RECIPES[recipe](rng)
        alpha = None
    elif recipe in RECIPES:
        res = RECIPES[recipe](rng, w, h)
        color, height, tilt, rough, alpha = res['color'], res['height'], res['tilt'], res['rough'], res['alpha']
    else:
        raise SystemExit(f'unknown recipe {recipe!r}')
    rough = np.clip(rough, 0.04, 1.0)
    if entry.get('alphaInColor'):
        if alpha is None:
            raise SystemExit(f'{recipe}: alphaInColor needs an alpha channel')
        rgba = np.concatenate([to_u8(color), to_u8(alpha)[..., None]], axis=-1)
        color_bytes = _png(Image.fromarray(rgba, 'RGBA'))
    else:
        color_bytes = _jpeg(Image.fromarray(to_u8(color)))
    files = {
        maps['color']['file']: color_bytes,
        # 4:4:4 for the normal map: chroma subsampling bends the vectors.
        maps['normal']['file']: _jpeg(Image.fromarray(normal_from_height(height, tilt)), subsampling=0),
        maps['roughness']['file']: _jpeg(Image.fromarray(to_u8(rough))),
    }
    for path, data in files.items():
        want = 'png' if path.endswith('.png') else 'jpeg'
        got = 'png' if data[:4] == b'\x89PNG' else 'jpeg'
        if want != got:
            raise SystemExit(f'{path}: the manifest names a .{want} file, the recipe encodes {got}')
    return files


def read_pool_file(pool: Path, rel: str) -> bytes:
    path = pool / rel
    if not path.is_file():
        raise SystemExit(f'missing pool file {rel}')
    data = path.read_bytes()
    if data.startswith(LFS_POINTER):
        raise SystemExit(f'{rel} is a Git LFS pointer, not an image: run `git lfs pull` first')
    return data


def measure(data: bytes, rel: str) -> dict:
    img = Image.open(io.BytesIO(data))
    fmt = {'JPEG': 'jpeg', 'PNG': 'png'}.get(img.format)
    if fmt is None:
        raise SystemExit(f'{rel}: unsupported image format {img.format}')
    want = 'png' if rel.endswith('.png') else 'jpeg'
    if fmt != want:
        raise SystemExit(f'{rel}: the bytes are {fmt} but the name says {want}')
    return {'file': rel, 'format': fmt, 'size': [img.size[0], img.size[1]], 'bytes': len(data),
            'sha256': hashlib.sha256(data).hexdigest()}


def set_stats(color: bytes, rough: bytes) -> dict:
    img = Image.open(io.BytesIO(color))
    rgb = np.asarray(img.convert('RGB'), dtype=float) / 255.0
    lum = 0.2126 * rgb[..., 0] + 0.7152 * rgb[..., 1] + 0.0722 * rgb[..., 2]
    # Three samples roughness from the green channel; for a grayscale map that is the value.
    rdec = np.asarray(Image.open(io.BytesIO(rough)).convert('RGB'), dtype=float)[..., 1] / 255.0
    stats = {
        'meanLuminance': round(float(lum.mean()), 4),
        'medianLuminance': round(float(np.median(lum)), 4),
        'minLuminance': round(float(lum.min()), 4),
        'meanRoughness': round(float(rdec.mean()), 4),
    }
    if img.mode in ('RGBA', 'LA'):
        stats['meanAlpha'] = round(float(np.asarray(img.convert('RGBA'), dtype=float)[..., 3].mean() / 255.0), 4)
    return stats


def update_manifest(manifest: dict, pool: Path, generated: dict[str, bytes]) -> dict:
    """Re-measure every file (generated bytes from ``generated``, the rest from the pool)."""
    def data_for(rel):
        return generated[rel] if rel in generated else read_pool_file(pool, rel)

    for name, entry in manifest['sets'].items():
        maps = entry['maps']
        for key in ('color', 'normal', 'roughness'):
            maps[key] = measure(data_for(maps[key]['file']), maps[key]['file'])
        entry['stats'] = set_stats(data_for(maps['color']['file']), data_for(maps['roughness']['file']))
        if entry['source']['kind'] == 'generated' and entry['source']['size'] != maps['color']['size']:
            raise SystemExit(f'{name}: generated at {maps["color"]["size"]}, manifest says {entry["source"]["size"]}')
    for photo in manifest['photos'].values():
        photo['image'] = measure(data_for(photo['image']['file']), photo['image']['file'])
    for preset in manifest['patchPresets']:
        preset['image'] = measure(data_for(preset['image']['file']), preset['image']['file'])
    return manifest


def dumps(manifest: dict) -> str:
    """Stable JSON: two-space indent, short numeric/string lists on one line."""
    text = json.dumps(manifest, indent=2, ensure_ascii=False)

    def collapse(m):
        items = [s.strip() for s in m.group(1).split(',')]
        return '[' + ', '.join(items) + ']'
    text = re.sub(r'\[\s*((?:-?[0-9.eE+-]+|"[^"\n]*")(?:\s*,\s*(?:-?[0-9.eE+-]+|"[^"\n]*"))*)\s*\]', collapse, text)
    return text + '\n'


def pool_images(pool: Path) -> set[str]:
    return {p.relative_to(pool).as_posix() for p in pool.rglob('*') if p.is_file() and p.suffix.lower() in IMAGE_SUFFIXES}


def referenced(manifest: dict) -> set[str]:
    files = {m['file'] for s in manifest['sets'].values() for m in s['maps'].values()}
    files |= {p['image']['file'] for p in manifest['photos'].values()}
    files |= {p['image']['file'] for p in manifest['patchPresets']}
    return files


