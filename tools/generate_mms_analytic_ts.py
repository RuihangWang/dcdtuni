#!/usr/bin/env python3
"""Regenerate src/frontend/react/src/liquid/mmsAnalytic.ts from the Stage-2b
acceptance receipt. IDEMPOTENT: output depends only on the JSON bytes (sha in
the header, no timestamp), so reruns on an unchanged receipt are no-ops and CI
can assert freshness with --check.

Source of truth: docs/benchmarks/liquid-dae-mms-product-20260928/analytic_curves.json
(the closed-form curves computed by tools/mms_product_acceptance.py; the DAE
curves stored alongside are the acceptance-run traces: never displayed, but
dae_solid_K is CONSUMED by the monitor's fixture-identity gate — see
solidTraceMatches in src/frontend/react/src/liquid/mmsOverlay.ts).
"""
import argparse
import hashlib
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
SRC = REPO / "docs/benchmarks/liquid-dae-mms-product-20260928/analytic_curves.json"
OUT = REPO / "src/frontend/react/src/liquid/mmsAnalytic.ts"


def render(raw: bytes, data: dict) -> str:
    sha = hashlib.sha256(raw).hexdigest()
    body = json.dumps(data, separators=(",", ":"), sort_keys=True)
    return f"""/** GENERATED by tools/generate_mms_analytic_ts.py — do not edit by hand.
 * Source: docs/benchmarks/liquid-dae-mms-product-20260928/analytic_curves.json
 * source_sha256: {sha}
 *
 * Closed-form reference curves for the MMS PRODUCT fixture only (1 CDU + 1
 * rack, dt = 1 s, N_t = 61, scenarios: load step 100->200 W at t=30 s and
 * supply-temperature step 290->295 K at t=30 s). Derivation:
 * docs/developer/liquid_dae_mms_product_derivation.md. Temperatures are
 * Kelvin; the UI converts. Comparable ONLY against runs replaying the same
 * fixture and scenario — the monitor enforces the time-axis match AND a
 * solid-trace identity check against dae_solid_K (±0.02 K), so a look-alike
 * 60 s / 1 s run of different physics is rejected.
 */
export interface MmsAnalyticCurves {{
  t_s: number[]
  analytic_solid_K: number[]
  analytic_secondary_K: number[]
  analytic_primary_K: number[]
  dae_solid_K: number[]
}}

export const mmsAnalyticSourceSha256 = '{sha}'

export const mmsAnalyticCurves: Record<'load' | 'supply', MmsAnalyticCurves> = {body}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the committed module differs")
    args = ap.parse_args()
    raw = SRC.read_bytes()
    data = json.loads(raw)
    text = render(raw, data)
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"STALE: {OUT} differs from regenerated content", file=sys.stderr)
            return 1
        print("mmsAnalytic.ts is fresh")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text)} chars, sha {hashlib.sha256(raw).hexdigest()[:16]})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
