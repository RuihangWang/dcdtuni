"""MMS product acceptance: DAE transient vs INDEPENDENT closed form.

Derivation: docs/developer/liquid_dae_mms_product_derivation.md.
Independence protocol: topology indices and parameter VALUES are read from the
compiled manifest / equation graph (data facts); the assembly FORMULAS are the
hand-derived ones re-implemented here in numpy; the production residual never
generates the analytic trajectory — it appears only in the one-directional
assembly audit (A.v vs the restricted JVP action).

Gates (all from the derivation note, none tuned):
  * steady-init equivalence: ||A x0 + B u0 + c||_inf <= 1e-9
  * assembly audit: rel err(A v vs -C*(JVP-restricted)) <= 1e-8
  * BE order in [0.85, 1.15] per scenario (dt 2 -> 1 -> 0.5 -> 0.25)
  * dt=0.25 max |T_dae - T_analytic| over {solid, secondary, primary}:
      reported as observed errors; sampled curvature is diagnostic, not a bound
  * per-step Newton scaled residual < 1e-8; |energy balance| < 1e-6 W;
    edge flows constant across the whole run
HX law: the fixture's heat_exchanger edge names it (params.hxModel, absent =
mixed-volumes; a data fact like the topology). Both laws are hand-derived here:
  mixed-volumes    Q = UA*(T_sec - T_pri)
  counterflow-ntu  Q = eps*C_min*(T_in - T_pi) + UA*[(T_sec - T_pri) - (1-a-b)*(T_in - T_pi)]
                   with the textbook counterflow eps(NTU, C_r), a = eps*C_min/C_sec_rate,
                   b = eps*C_min/C_pri_rate (constant flows make both linear).
Usage: --fixture selects another .liquidrun (e.g. one regenerated by
tools/generate_mms_product.mjs or a counterflow variant); default is the frozen one.
Diagnostic script, not product code. CPU only, float64.
"""
